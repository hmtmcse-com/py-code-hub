# ============================================================
# ROUTER OUTPUT
# ============================================================

def generate_output_rules(
    plan: PCCPlan,
) -> str:
    """
    Router-originated NEW connections are intentionally NOT
    PCC classified.

    Existing marked connections are routed according to their
    connection mark.
    """

    lines = [
        "# ============================================================",
        "# AUTO-PCC ROUTER OUTPUT",
        "# ============================================================",
        "#",
        "# Router-originated NEW connections are NOT PCC",
        "# classified by this generator.",
        "#",
        "# Existing marked connections are routed according",
        "# to their connection mark.",
        "#",
        "/ip firewall mangle",
    ]

    for isp in plan.isps:

        lines.append(
            "add "
            "chain=output "
            f"connection-mark={isp.connection_mark} "
            "dst-address-type=!local "
            "action=mark-routing "
            f"new-routing-mark={isp.routing_mark} "
            "passthrough=no "
            f'comment="{auto_comment("OUTPUT-ROUTE", isp.name)}"'
        )

    return "\n".join(lines) + "\n"


# ============================================================
# COMPLETE MANGLE CONFIG
# ============================================================

def generate_mangle_config(
    plan: PCCPlan,
) -> str:

    routing_tables = ", ".join(
        isp.routing_mark
        for isp in plan.isps
    )

    sections = [
        """# ============================================================
# AUTO-GENERATED MIKROTIK PCC CONFIGURATION
# ============================================================
#
# This configuration manages ONLY AUTO-PCC rules.
#
# ============================================================
# MANAGED BY THIS GENERATOR
# ============================================================
#
#   - WAN inbound connection marking
#   - PCC connection marking
#   - Connection mark -> routing mark
#   - Inbound reply routing
#   - Existing marked router-output routing
#
# ============================================================
# NOT MANAGED BY THIS GENERATOR
# ============================================================
#
#   - NET-INTERNAL bypass
#   - NET-VPN bypass
#   - Firewall
#   - NAT
#   - Routing table creation
#   - WAN routes
#   - Failover routes
#   - WireGuard
#
# ============================================================
""",

        generate_pcc_model_documentation(plan),

        generate_bucket_mapping(plan),

        "# ============================================================\n"
        "# REQUIRED ROUTING TABLES\n"
        "# ============================================================\n"
        "#\n"
        f"#   {routing_tables}\n"
        "#\n"
        "# These routing tables must already exist.\n"
        "#\n",

        "# ============================================================\n"
        "# REQUIRED MANGLE ORDER\n"
        "# ============================================================\n"
        "#\n"
        "# Manual bypass rules MUST exist before AUTO-PCC:\n"
        "#\n"
        "#   1. NET-INTERNAL bypass\n"
        "#   2. NET-VPN bypass\n"
        "#\n"
        "# Then AUTO-PCC:\n"
        "#\n"
        "#   3. WAN inbound connection marking\n"
        "#   4. PCC connection marking\n"
        "#   5. Connection mark -> routing mark\n"
        "#   6. Inbound reply routing\n"
        "#   7. Router output routing\n"
        "#\n"
        "# ============================================================\n",

        generate_cleanup(),

        generate_inbound_connection_rules(plan),

        generate_pcc_connection_rules(plan),

        generate_policy_routing_rules(plan),

        generate_inbound_reply_rules(plan),

        generate_output_rules(plan),
    ]

    return "\n".join(sections)


